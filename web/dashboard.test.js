test("a record is findable by the name a person would search for", () => {
  /* WHY THIS TEST EXISTS, AND WHY IT CHANGED ONCE.
     The dashboard listed `refractive-error` under *it works and it does not
     arrive* and **the word "glasses" appeared nowhere on the page**. Slugs are
     the register's handles, not anybody's vocabulary.

     The first fix put the whole `also` list in a clipped span so browser find
     would reach it. That was WORSE than not fixing it: ctrl-F matched, scrolled,
     and highlighted nothing visible — a page that looks broken. **Text search
     can find and a reader cannot see is not findability**, so this now asserts
     the plain name is in VIEW and that nothing on the page is visually clipped
     to fake a match. */
  const { html, rendered, slim } = boot();
  const withCommon = here(slim.filter(r => r.common));
  assert.ok(withCommon.length > 15,
    "slim.js should carry `common` — run check.py --build");

  assert.ok(!/clip\s*:\s*rect/.test(html),
    "something on this page is visually clipped; if it is there for browser " +
    "find, it is a false match a reader cannot see");

  const missing = here(withCommon
    .filter(r => !rendered.includes(`<span class="common">${r.common}</span>`))
    .map(r => r.slug));
  assert.deepEqual(missing, [],
    "records whose ordinary name is not rendered:\n" + missing.join("\n"));

  // the specific case that prompted all of it
  assert.match(rendered, /<span class="common">glasses<\/span>/,
    "somebody looking for glasses must see the word, not just match it");
  assert.match(rendered, /<span class="common">sleeping sickness<\/span>/);
});

test("chip fields are not ordered by deaths", () => {
  /* THE BIAS THIS PAGE EXISTS TO CORRECT, REINTRODUCED IN THE PRESENTATION
     LAYER. Sorting by mortality put the largest access failure in the world at
     the bottom of the section about access failures, because glasses kill
     nobody. Alphabetical is the neutral order and this asserts it. */
  const { rendered, snap, slim } = boot();
  const bySlug = Object.fromEntries(slim.map(r => [r.slug, r]));
  for (const k of BUCKET_ORDER) {
    const names = chipSlugs(sectionBody(rendered, snap.buckets.names[k]))
      .map(s => bySlug[s].name || s);
    assert.deepEqual(names, names.slice().sort((a, b) => a.localeCompare(b)),
      `${k}: chips are not in alphabetical order`);
  }
});

test("a bucket's exemplars come from buckets.yaml and are members of it", () => {
  /* The exemplars exist because alphabetical membership hides things — the
     largest unmet need in the register is called *Uncorrected refractive error*
     and sorts 66th of 68. They are a stated editorial choice, so they must come
     from the definitions file rather than the page, and they must actually be in
     the bucket they illustrate or the section is lying about its own contents. */
  const { html, rendered, snap } = boot();
  const defs = snap.buckets.defs;
  let shown = 0;
  for (const [slug, def] of Object.entries(defs)) {
    const ex = here(def.examples);
    if (!ex.length) continue;
    const body = sectionBody(rendered, snap.buckets.names[slug]);
    const drawn = [...body.matchAll(/<a class="chip ex" data-slug="([a-z0-9-]+)"/g)]
      .map(m => m[1]);
    assert.deepEqual(drawn, ex, `${slug}: exemplars drawn do not match buckets.yaml`);
    shown += drawn.length;
    // and each must belong to the thing it illustrates
    for (const e of drawn) {
      const m = snap.buckets.members[e];
      assert.ok(m, `${slug} names ${e} as an example and no such record exists`);
      const inIt = m.a === slug || (m.b || []).includes(slug);
      assert.ok(inIt, `${slug} names ${e} as an example, but ${e} is not in it`);
    }
    assert.ok(!html.includes(ex.join(", ")),
      `${slug}: the page carries its own copy of the examples`);
  }
  assert.ok(shown > 20, "expected exemplars on most sections");
});
