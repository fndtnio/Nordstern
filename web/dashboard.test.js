/* =====================================================================
 * Nordstern dashboard tests — run with:  node --test web/
 *
 * THE RULE THIS FILE ENFORCES, AND IT IS THE ONLY REASON IT EXISTS:
 *
 *   **Every figure on the dashboard links to the query that produces it, and
 *   that query must actually return that number.**
 *
 * A statistic you cannot express as a query is one nobody can check. Worse, a
 * statistic whose query returns something *else* is a page telling a visitor
 * one thing and the tool telling them another — and the visitor will believe
 * the page, because it is the one with the big number on it.
 *
 * So this file renders the real dashboard against the real generated
 * artifacts, pulls every `query.html?q=…` link out of the result along with the
 * figure printed beside it, runs each query through the real query engine, and
 * compares. It is the same discipline as the two `index.md` guards in
 * test_check.py: recompute rather than trust.
 *
 * It also pins the second rule — that the page owns no derivation. Every number
 * must come from `snapshots.js` or `slim.js`, both generated by check.py.
 * ===================================================================== */
const { test } = require("node:test");
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const vm = require("node:vm");

const DIR = __dirname;
const Query = require("./query.js");

/* ---- render the real page in a fake DOM ----------------------------- */
function boot() {
  const html = fs.readFileSync(path.join(DIR, "index.html"), "utf8");
  const inline = [...html.matchAll(/<script>([\s\S]*?)<\/script>/g)];
  assert.equal(inline.length, 1, "expected exactly one inline <script>");

  const els = {};
  const get = id => (els[id] ||= { id, innerHTML: "" });
  ["prov", "body", "series"].forEach(get);

  const sandbox = {
    window: {},
    document: { getElementById: get },
    location: { href: "" },
    encodeURIComponent, decodeURIComponent,
    JSON, Object, Array, Set, Map, String, Number, Math, RegExp, console,
  };
  sandbox.window = sandbox;

  for (const f of ["banner.js", "slim.js", "snapshots.js", "engpass-snapshots.js"])
    vm.runInContext(fs.readFileSync(path.join(DIR, f), "utf8"), vm.createContext(sandbox));
  vm.runInContext(inline[0][1], sandbox, { filename: "index.html:inline" });

  const rendered = els.prov.innerHTML + els.body.innerHTML + els.series.innerHTML;
  return { html, rendered, sandbox,
           snap: sandbox.window.NORDSTERN_SNAPSHOTS.at(-1),
           esnap: sandbox.window.ENGPASS_SNAPSHOTS.at(-1),
           slim: sandbox.window.NORDSTERN_SLIM };
}

/* Pull every query link out of the rendered markup. */
function links(rendered) {
  return [...rendered.matchAll(/query\.html\?q=([^"'#]+)/g)]
    .map(m => decodeURIComponent(m[1]));
}

/* data.js assigns to `window` at top level, so it cannot be require()d —
   it has to run inside a context that has one. Same trick as tool.test.js. */
function loadRecords() {
  const s = { window: {}, JSON, Object, Array, console };
  s.window = s;
  vm.createContext(s);
  vm.runInContext(fs.readFileSync(path.join(DIR, "data.js"), "utf8"), s);
  return s.window.NORDSTERN.records;
}

