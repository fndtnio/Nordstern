/* ---- the burden-weighted figure ------------------------------------- */

/* This section makes a CLAIM — that the biggest knowledge gaps are in the
 * common diseases, not the rare terrible ones — and a reader will take the
 * chart as evidence for it. So the claim is asserted here against the real
 * artifacts. If a re-rating overturns it, this fails and the prose gets
 * rewritten, rather than the page going quietly on saying something untrue. */
test("the burden-weighted figure states its exclusions and its claim holds", () => {
  const { rendered, snap, slim } = boot();
  const text = rendered.replace(/<[^>]+>/g, " ").replace(/\s+/g, " ");

  // It must say how many records it cannot see. A chart that silently drops a
  // sixth of the register reads as though it covered everything.
  const missing = snap.records.active - snap.gaps.rated;
  assert.ok(missing > 0, "expected some records to be unrateable");
  assert.match(text, new RegExp(`${missing} records are missing from the chart`),
               "the figure must state how many records it excludes");
  assert.match(text, /Rabies is the case that forces that exclusion/,
               "the exclusion must name the record that forces it, not just the rule");
  assert.match(text, /construct, not a measurement/,
               "the proxy caveat must survive — efficacy is not a mortality reduction");

  // The claim itself.
  const rated = slim.filter(r => r.knowledge_gap != null);
  const top = rated.reduce((a, b) => (b.knowledge_gap > a.knowledge_gap ? b : a));
  const helpless = slim.filter(r => r.efficacy === 0)
                       .reduce((s, r) => s + (r.deaths || 0), 0);
  assert.ok(top.knowledge_gap > 10 * helpless,
    `the section claims the common diseases hold the bigger gaps: ${top.slug} is ` +
    `${top.knowledge_gap} against ${helpless} total deaths where nothing works`);

  // Every dot on the chart is a record the register can actually rate.
  assert.equal(rated.length, snap.gaps.rated,
               "slim.js and the snapshot disagree about how many records carry a gap");
});

test("the two gaps partition the burden, in the snapshot as in the records", () => {
  const { snap, slim } = boot();
  const k = slim.reduce((s, r) => s + (r.knowledge_gap || 0), 0);
  const d = slim.reduce((s, r) => s + (r.delivery_gap || 0), 0);
  assert.ok(Math.abs(k - snap.gaps.knowledge) < 1, "slim and snapshot disagree on knowledge");
  assert.ok(Math.abs(d - snap.gaps.delivery) < 1, "slim and snapshot disagree on delivery");
  for (const r of slim.filter(x => x.knowledge_gap != null))
    assert.ok(r.knowledge_gap + r.delivery_gap <= r.deaths + 1e-6,
              `${r.slug}: the gaps exceed the burden they partition`);
});

