/* The load-bearing one. A figure and its link must agree.
 *
 * Only checked for links whose printed figure is a plain count of records —
 * a `stat()` card or a bar row. Ratios, medians and per-blocker counts are
 * exercised by the two tests above and by the snapshot tests in test_check.py,
 * because the query engine counts RECORDS and those numbers do not. */
test("every record-count figure matches what its query returns", () => {
  const { rendered } = boot();
  const recs = loadRecords();

  // stat cards carrying data-count="records" — the marker `stat()` adds only
  // when a query was supplied
  const cards = [...rendered.matchAll(
    /<a class="q" href="query\.html\?q=([^"]+)"><div class="card">\s*<div class="stat[^"]*" data-count="records">([^<]+)<\/div>/g)];
  // bar rows likewise. A row marked data-count="items" is counting blockers or
  // mentions, and the query — which counts records — correctly returns a
  // different number. That distinction is the reason this test exists.
  const rows = [...rendered.matchAll(
    /href="query\.html\?q=([^"]+)"[^>]*>[^<]*<\/a>\s*<\/td>\s*<td class="num" data-count="records">([\d,]+)<\/td>/g)];

  assert.ok(cards.length >= 6, `found only ${cards.length} record-count stat cards`);
  assert.ok(rows.length >= 20, `found only ${rows.length} record-count bar rows`);

  const mismatches = [];
  for (const [, rawQ, rawN] of [...cards, ...rows]) {
    const q = decodeURIComponent(rawQ);
    const shown = rawN.replace(/,/g, "").trim();
    if (!/^\d+$/.test(shown)) continue;      // ratios, percentages, medians
    const got = Query.run(recs, q).records.length;
    if (got !== Number(shown))
      mismatches.push(`"${q}" shows ${shown}, returns ${got}`);
  }
  assert.deepEqual(mismatches, [],
    "a figure disagrees with its own query:\n  " + mismatches.join("\n  "));
});

